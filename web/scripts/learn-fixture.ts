/**
 * Picks the Learn area's practice positions and puzzles from the output of
 * `scripts/learn-mine.ts` and writes `src/learn/positions.ts`.
 *
 *   node scripts/learn-fixture.ts <mined.json>...
 *   node scripts/learn-fixture.ts --variants <mined.json>...
 *
 * With `--variants` it reads runs of `learn-mine.ts --variant` and writes
 * `src/learn/variant-positions.ts` instead, leaving `positions.ts` alone.
 *
 * Every pick is checked again with the techniques as they are now, so a run
 * mined with older finders can't put a wrong position in the fixture.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { solve } from "../src/generator/solver.ts";
import { type LayoutData, dataLayout, decodeCand } from "../src/learn/positions-format.ts";
import { type State, isSolved, parseGrid, stateOf } from "../src/learn/state.ts";
import { TECHNIQUES, type Technique, VARIANT_TECHNIQUES, easierApplies, solveByLogic, techniquesIn } from "../src/learn/techniques.ts";
import type { MinedPosition, MinedPuzzle } from "./learn-mine.ts";

/** Practice positions a technique. */
const PER_TECHNIQUE = 4;

const stateFor = (p: MinedPosition): State =>
  stateOf(parseGrid(p.grid), p.cand ? decodeCand(p.cand) : undefined, p.layout ? dataLayout(p.layout) : undefined);

/** How hard a position looks: more empty squares for a placement, a bigger pattern for an elimination. */
const weight = (t: Technique, p: MinedPosition): number => (t.places ? p.empty : p.marks * 20 + p.eliminations);

function stillValid(t: Technique, p: MinedPosition): boolean {
  const state = stateFor(p);
  return t.find(state).length > 0 && !easierApplies(state, t.id);
}

function pickPositions(t: Technique, mined: MinedPosition[]): MinedPosition[] {
  // Variant positions: only where the grader agrees, and an elimination removes one to four candidates (each one is removed by hand).
  const own = mined.filter((p) => p.technique === t.id && p.agrees !== false && (t.places || !p.layout || p.eliminations <= 4));
  // One answer on the board is clearest, where there are enough of those to choose from.
  const single = own.filter((p) => p.found === 1);
  const pool = (t.places || single.length < PER_TECHNIQUE * 4 ? own : single)
    .sort((a, b) => weight(t, a) - weight(t, b) || a.seed - b.seed);
  const picked: MinedPosition[] = [];
  for (const at of [0, 0.4, 0.75, 0.97]) {
    for (let i = Math.max(0, Math.floor(at * (pool.length - 1))); i < pool.length; i++) {
      const p = pool[i]!;
      if (picked.some((q) => q.seed === p.seed || q.grid === p.grid) || !stillValid(t, p)) continue;
      picked.push(p);
      break;
    }
  }
  return picked;
}

function pickPuzzle(t: Technique, puzzles: MinedPuzzle[]): MinedPuzzle | null {
  const own = puzzles.filter((p) => p.hardest === t.id).sort((a, b) => (b.used[t.id] ?? 0) - (a.used[t.id] ?? 0) || a.seed - b.seed);
  for (const p of own) {
    const { steps, end } = solveByLogic(stateOf(parseGrid(p.givens)));
    if (isSolved(end) && steps.some((s) => s.technique === t.id)) return p;
  }
  return null;
}

/** The layout fields of a generated entry. */
function layoutFields(data: LayoutData | undefined): string {
  if (!data) return "";
  if (data.diagonal) return ", diagonal: true";
  return data.regions !== undefined ? `, regions: "${data.regions}"` : `, cages: "${data.cages}"`;
}

/** A variant puzzle the Learn techniques finish in its layout, with `t` used and the hardest step. */
function pickVariantPuzzle(t: Technique, puzzles: MinedPuzzle[]): MinedPuzzle | null {
  const own = puzzles.filter((p) => p.hardest === t.id).sort((a, b) => (b.used[t.id] ?? 0) - (a.used[t.id] ?? 0) || a.seed - b.seed);
  for (const p of own) {
    const layout = dataLayout(p.layout!);
    const order = techniquesIn(layout).map((x) => x.id);
    const { steps, end } = solveByLogic(stateOf(parseGrid(p.givens), undefined, layout));
    if (isSolved(end) && Math.max(...steps.map((s) => order.indexOf(s.technique))) === order.indexOf(t.id)) return p;
  }
  return null;
}

function variants(mined: MinedPosition[], puzzles: MinedPuzzle[]): void {
  const lines: string[] = [
    "// Generated by scripts/learn-fixture.ts --variants from puzzles mined with scripts/learn-mine.ts --variant. Don't edit by hand.",
    "// test/learn-positions.test.ts checks every entry.",
    'import type { PositionData, PuzzleData } from "./positions-format.ts";',
    "",
    "/** Practice positions of the variant lessons by technique id, as in positions.ts, each with its layout. */",
    "export const VARIANT_POSITIONS: Record<string, readonly PositionData[]> = {",
  ];
  for (const t of VARIANT_TECHNIQUES) {
    lines.push(`  ${t.id}: [`);
    for (const p of pickPositions(t, mined)) {
      lines.push(`    { grid: "${p.grid}", solution: "${p.solution}"${p.cand ? `, cand: "${p.cand}"` : ""}${layoutFields(p.layout)} },`);
    }
    lines.push("  ],");
  }
  lines.push("};", "", "/** A whole variant puzzle by technique id. */", "export const VARIANT_PUZZLES: Record<string, PuzzleData> = {");
  for (const t of VARIANT_TECHNIQUES) {
    const p = pickVariantPuzzle(t, puzzles);
    if (p) lines.push(`  ${t.id}: { givens: "${p.givens}", solution: "${p.solution}"${layoutFields(p.layout)} },`);
  }
  lines.push("};", "");
  writeFileSync(new URL("../src/learn/variant-positions.ts", import.meta.url), lines.join("\n"));
}

function main(): void {
  const variantRun = process.argv[2] === "--variants";
  const mined: MinedPosition[] = [];
  const puzzles: MinedPuzzle[] = [];
  for (const file of process.argv.slice(variantRun ? 3 : 2)) {
    const run = JSON.parse(readFileSync(file, "utf8")) as { positions: MinedPosition[]; puzzles: MinedPuzzle[] };
    mined.push(...run.positions);
    puzzles.push(...run.puzzles);
  }
  if (variantRun) {
    variants(mined, puzzles);
    return;
  }
  const lines: string[] = [
    "// Generated by scripts/learn-fixture.ts from puzzles mined with scripts/learn-mine.ts. Don't edit by hand.",
    "// test/learn-positions.test.ts checks every entry.",
    'import type { PositionData, PuzzleData } from "./positions-format.ts";',
    "",
    "/** Practice positions by technique id, easiest first: in each, the technique is the easiest step open. */",
    "export const POSITIONS: Record<string, readonly PositionData[]> = {",
  ];
  for (const t of TECHNIQUES) {
    lines.push(`  ${t.id}: [`);
    for (const p of pickPositions(t, mined)) {
      const solution = solve(parseGrid(p.grid))!.join("");
      lines.push(`    { grid: "${p.grid}", solution: "${solution}"${p.cand ? `, cand: "${p.cand}"` : ""} },`);
    }
    lines.push("  ],");
  }
  lines.push("};", "", "/** A whole puzzle by technique id: the technique is the hardest one it needs. */", "export const PUZZLES: Record<string, PuzzleData> = {");
  for (const t of TECHNIQUES) {
    const p = pickPuzzle(t, puzzles);
    if (p) lines.push(`  ${t.id}: { givens: "${p.givens}", solution: "${p.solution}" },`);
  }
  lines.push("};", "");
  writeFileSync(new URL("../src/learn/positions.ts", import.meta.url), lines.join("\n"));
}

if (import.meta.main) main();
